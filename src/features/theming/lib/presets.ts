import type { BuiltInPreset, ModeTheme, SimpleTokens, TokenValues } from "../types";
import { SHADCN_TOKENS } from "../types";
import { SHADCN_DARK_DEFAULTS, SHADCN_LIGHT_DEFAULTS } from "./defaults";

// ── Helpers ───────────────────────────────────────────────────────────────────

function lv(overrides: Partial<TokenValues>): TokenValues {
  return { ...SHADCN_LIGHT_DEFAULTS, ...overrides };
}

function dv(overrides: Partial<TokenValues>): TokenValues {
  return { ...SHADCN_DARK_DEFAULTS, ...overrides };
}

function toModeTheme(tv: TokenValues): ModeTheme {
  const result: Partial<ModeTheme> = {};
  for (const t of SHADCN_TOKENS) {
    result[t] = { value: tv[t], source: "override" as const };
  }
  return result as ModeTheme;
}

function simplePreset(
  name: string,
  description: string,
  lightOverrides: Partial<TokenValues>,
  darkOverrides: Partial<TokenValues>,
): BuiltInPreset {
  const lt = lv(lightOverrides);
  const dk = dv(darkOverrides);
  return {
    name,
    description,
    level: "simple",
    simple: {
      foreground: lt.foreground,
      background: lt.background,
      primary: lt.primary,
      secondary: lt.secondary,
      accent: lt.accent,
    },
    light: toModeTheme(lt),
    dark: toModeTheme(dk),
  };
}

function advancedPreset(
  name: string,
  description: string,
  lightOverrides: Partial<TokenValues>,
  darkOverrides: Partial<TokenValues>,
): BuiltInPreset {
  const lt = lv(lightOverrides);
  const dk = dv(darkOverrides);
  return {
    name,
    description,
    level: "advanced",
    simple: {
      foreground: lt.foreground,
      background: lt.background,
      primary: lt.primary,
      secondary: lt.secondary,
      accent: lt.accent,
    },
    light: toModeTheme(lt),
    dark: toModeTheme(dk),
  };
}

